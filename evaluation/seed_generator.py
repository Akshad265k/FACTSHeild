"""
Seeded error generator -- programmatically injects known errors into a clean
multilingual release to create a labelled benchmark dataset.

40 seeded test cases (10 number + 10 date + 10 name + 10 location) are
generated by applying deterministic text transformations.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field


@dataclass
class SeedCase:
    """A single seeded-error test case."""

    id: str
    category: str            # "number" | "date" | "name" | "location"
    description: str
    language_affected: str   # "English" | "Hindi" | "Marathi"
    fact_type: str           # "number" | "date" | "name" | "location"
    expected_value: str      # Canonical value that the QC engine should detect as missing
    versions: dict[str, str]
    expected_detection: bool = True


# ---------------------------------------------------------------------------
# Low-level text manipulation helpers
# ---------------------------------------------------------------------------


def _rm(text: str, value: str) -> str:
    """Remove first occurrence of *value* from *text*."""
    return text.replace(value, "", 1)


def _rm_all(text: str, value: str) -> str:
    """Remove all occurrences of *value* from *text*."""
    return text.replace(value, "")


def _sub(text: str, old: str, new: str) -> str:
    """Replace first occurrence of *old* with *new* in *text*."""
    return text.replace(old, new, 1)


def _sub_all(text: str, old: str, new: str) -> str:
    """Replace all occurrences of *old* with *new* in *text*."""
    return text.replace(old, new)


def _inc(value: str, delta: int) -> str:
    """Increment an integer string by *delta*, clamped to >= 1."""
    try:
        return str(max(1, int(value) + delta))
    except ValueError:
        return value


